"""The preset the instrument starts on: Vital's default values, with media of this package's own.

`patchbay_vital.instrument.VitalInstrument` loads this preset into the plugin when it is built, so
its model never comes from the plugin's state and is the same on every machine and every instance
(the instrument spec's shape.md, Decision 2). Vital's own starting state is neither: its wavetable
and its noise sample are Vital's, which its licence bars redistributing, and two fresh instances
already differ in the sample (the host spec's `verification/probes.txt`). A patch that names
values and nothing else is laid over this preset too (`patchbay_vital.patch`).

What `data/start.vital` holds:

- every hosted parameter at the value the plugin starts from, the map's `preset_default`, which
  `data/parameters.json` ships already;
- 64 empty modulation slots, and the metadata a save writes, naming this package as its author;
- the five sections a 1.6.4 save holds, in that save's structure, each generated here and none of
  it Vital's: one ramp, `i / 1024 - 1` over 2,048 samples, as each oscillator's wavetable, which
  is exact in float32 on any machine and has harmonics for a filter to cut; a two-point line as
  each LFO's and each warp's shape; a 16-sample ramp as the sample; and the save's own seed for
  each random source.

The file is generated, never edited: `start_text` writes it from a map, and the census writes it
beside the map and the key list, all three replaced together or not at all, so a new Vital's
census cannot leave it stale. It is written here as text, not through the preset's models, because
the models hold a key to the committed key list and the census must still write all three on a
Vital whose keys that list lacks. The unit tests hold the committed file to this text, this text to
the format's own writer byte for byte, its floats to the map's defaults, and every section to its
formula, written out again there.

Shipping the file is the owner's licence call of 2026-11-15, not legal advice, and is revisited
before any release (the instrument spec's shape.md, Decision 3).
"""

import base64
import functools
import importlib.resources
import json
import struct

from patchbay_vital.format import loads, write_object, write_string
from patchbay_vital.grisu2 import format_float
from patchbay_vital.parameters import ParameterMap
from patchbay_vital.preset import MODULATION_SLOTS, MODULATIONS_KEY, VitalPreset

AUTHOR = "patchbay-vital"
"""Who made the preset and its wavetable: this package, as the file says of itself."""

COMMENTS = "Vital's default values with media generated by patchbay-vital."

PRESET_NAME = "Start"

MACROS = ("MACRO 1", "MACRO 2", "MACRO 3", "MACRO 4")
"""The four macros' names, as a 1.6.4 save of an unchanged preset writes them."""

WAVETABLE_SAMPLES = 2048
"""A wavetable frame's length, as a 1.6.4 save holds one."""

OSCILLATORS, LFOS, WARPS, RANDOMS = 3, 8, 3, 3
"""How many entries a 1.6.4 save holds in `wavetables`, `lfos`, `custom_warps`, `random_values`."""

SAMPLE = tuple((index - 8) * 1000 for index in range(16))
"""The sample's 16-bit values: a ramp from -8000 in steps of 1000."""

SAMPLE_RATE = 44100

RANDOM_SEED = 4
"""The seed a 1.6.4 save of an unchanged preset writes for each random source."""

_DATA = "data/start.vital"
_EMPTY_SLOT = '{"destination":"","source":""}'


def _section(value: object) -> str:
    """Write a section as a preset holds it: keys sorted at every depth, no whitespace.

    The format holds a section as the text the file held and never writes one from values, so
    this is the one writer of nested JSON; strings and the objects of the file's top level and
    `settings` go through the format's own writers.
    """
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def _ramp() -> str:
    """Return the wavetable's one frame, a ramp from -1 in steps of 1/1024, as the file holds it.

    Little-endian float32 samples in base64. Each value is a whole number of 1024ths below 2 in
    magnitude, so it is a float32 exactly and no rounding or libm decides a bit of it.
    """
    samples = (index / 1024 - 1 for index in range(WAVETABLE_SAMPLES))
    return base64.b64encode(struct.pack(f"<{WAVETABLE_SAMPLES}f", *samples)).decode("ascii")


def _line(name: str) -> dict[str, object]:
    """Return a shape of two points, a straight line from (0, 1) to (1, 0), under a name."""
    return {
        "name": name,
        "num_points": 2,
        "points": [0.0, 1.0, 1.0, 0.0],
        "powers": [0.0, 0.0],
        "smooth": False,
    }


def _wavetable(version: str) -> dict[str, object]:
    """Return one oscillator's wavetable: a single frame holding the ramp."""
    component = {
        "interpolation": 1,
        "interpolation_style": 1,
        "keyframes": [{"position": 0, "wave_data": _ramp()}],
        "type": "Wave Source",
    }
    return {
        "author": AUTHOR,
        "full_normalize": True,
        "groups": [{"components": [component]}],
        "name": "Ramp",
        "remove_all_dc": True,
        "version": version,
    }


def sections(version: str) -> dict[str, str]:
    """Return the five sections of the start preset, each as the text the file holds.

    `version` is the Vital the preset is for, which each wavetable names.
    """
    sample = {
        "length": len(SAMPLE),
        "name": "Ramp",
        "sample_rate": SAMPLE_RATE,
        "samples": base64.b64encode(struct.pack(f"<{len(SAMPLE)}h", *SAMPLE)).decode("ascii"),
    }
    return {
        "custom_warps": _section([_line(f"Line {number}") for number in range(1, WARPS + 1)]),
        "lfos": _section([_line(f"Line {number}") for number in range(1, LFOS + 1)]),
        "random_values": _section([{"seed": RANDOM_SEED}] * RANDOMS),
        "sample": _section(sample),
        "wavetables": _section([_wavetable(version)] * OSCILLATORS),
    }


def start_text(found: ParameterMap) -> str:
    """Return the text of the start preset for a map: its defaults, empty slots and the sections.

    The text `format.dumps` writes for the same preset, byte for byte, which a unit test holds on
    the committed map. Written from the map alone, so the census can write it for any Vital it
    measured.
    """
    settings: dict[str, str] = {
        record.preset_key: format_float(record.preset_default) for record in found.parameters
    }
    settings |= sections(found.vital_version)
    settings[MODULATIONS_KEY] = "[" + ",".join([_EMPTY_SLOT] * MODULATION_SLOTS) + "]"
    members = {
        "author": write_string(AUTHOR),
        "comments": write_string(COMMENTS),
        "preset_name": write_string(PRESET_NAME),
        "preset_style": write_string(""),
        "settings": write_object(settings),
        "synth_version": write_string(found.vital_version),
    }
    members |= {f"macro{number}": write_string(name) for number, name in enumerate(MACROS, 1)}
    return write_object(members)


@functools.cache
def start_preset() -> VitalPreset:
    """Return the committed start preset, read on the first call.

    Everything it holds is immutable, so every caller shares the one model.
    """
    text = importlib.resources.files("patchbay_vital").joinpath(_DATA).read_text(encoding="utf-8")
    return loads(text)
