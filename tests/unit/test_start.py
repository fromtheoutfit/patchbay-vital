"""The start preset is Vital's defaults with media of this package's own, and cannot drift.

The committed `data/start.vital` is held four ways: to the text the package writes from the
committed map, to the format's own writer byte for byte, to the map's defaults float for float,
and each of its sections to its formula, written out again here from primitives so that a change
to the file or to `start.py` alone fails by name. Nothing here is Vital's: the structure is a
1.6.4 save's, and every sample, shape and name in it is generated.
"""

import base64
import json
import struct
from pathlib import Path

import pytest
from patchbay import ParameterId, PresetKey

from patchbay_vital import dumps, loads
from patchbay_vital.errors import UnknownSettingError
from patchbay_vital.format import split_modulations
from patchbay_vital.parameters import ParameterMap, parameter_map
from patchbay_vital.preset import MODULATION_SLOTS
from patchbay_vital.start import start_preset, start_text

_FILE = Path("src") / "patchbay_vital" / "data" / "start.vital"
_PARAMETERS = 903
_SLOT_FLOATS = 448


def _committed(pytestconfig: pytest.Config) -> str:
    return (pytestconfig.rootpath / _FILE).read_text(encoding="utf-8")


def _line(name: str) -> dict[str, object]:
    """Return the one shape the preset holds, written out: a line from (0, 1) to (1, 0)."""
    return {
        "name": name,
        "num_points": 2,
        "points": [0.0, 1.0, 1.0, 0.0],
        "powers": [0.0, 0.0],
        "smooth": False,
    }


def _section(name: str) -> object:
    """Return one of the start preset's sections, parsed."""
    return json.loads(start_preset().opaque[PresetKey(name)])


def test_the_committed_file_is_what_the_package_writes_from_the_committed_map(
    pytestconfig: pytest.Config,
) -> None:
    """The file is generated: the map and the file are one census's, and neither moved alone."""
    assert start_text(parameter_map()) == _committed(pytestconfig)


def test_the_file_comes_back_byte_for_byte_through_the_format(pytestconfig: pytest.Config) -> None:
    """The text is the one `dumps` writes for the preset it reads as, to the byte."""
    text = _committed(pytestconfig)
    assert dumps(loads(text)) == text
    assert start_preset() == loads(text)
    assert start_preset() is start_preset()


def test_every_float_is_the_map_s_default() -> None:
    """All 903 parameters, the 448 slot floats among them, at the value the plugin starts from."""
    preset = start_preset()
    _, slots = split_modulations(preset.modulations)
    floats = {**preset.settings.values, **slots}
    defaults = {record.preset_key: record.preset_default for record in parameter_map().parameters}
    assert len(defaults) == _PARAMETERS
    assert len(slots) == _SLOT_FLOATS
    assert floats == defaults


def test_every_slot_is_empty_and_the_metadata_names_this_package() -> None:
    """Nothing is routed, and the preset says of itself who made it and what it holds."""
    preset = start_preset()
    assert len(preset.modulations) == MODULATION_SLOTS
    assert all(slot.is_empty and slot.line_mapping is None for slot in preset.modulations)
    assert preset.author == "patchbay-vital"
    assert preset.comments == "Vital's default values with media generated by patchbay-vital."
    assert preset.preset_name == "Start"
    assert preset.preset_style == ""
    assert (preset.macro1, preset.macro2) == ("MACRO 1", "MACRO 2")
    assert (preset.macro3, preset.macro4) == ("MACRO 3", "MACRO 4")
    assert preset.synth_version == parameter_map().vital_version
    assert preset.tuning is None
    assert not preset.trailing_newline


def test_the_sections_are_the_five_a_save_holds() -> None:
    """No section beside the ones generated below."""
    assert sorted(start_preset().opaque) == [
        "custom_warps",
        "lfos",
        "random_values",
        "sample",
        "wavetables",
    ]


def test_each_wavetable_is_one_frame_of_a_ramp_exact_in_float32() -> None:
    """Three wavetables, each a single frame: the 2,048 samples (i - 1024) / 1024, bit for bit."""
    ramp = [(index - 1024) / 1024 for index in range(2048)]
    packed = struct.pack("<2048f", *ramp)
    assert list(struct.unpack("<2048f", packed)) == ramp  # each is a float32 exactly
    assert (ramp[0], ramp[1024], ramp[-1]) == (-1.0, 0.0, 0.9990234375)
    wavetable = {
        "author": "patchbay-vital",
        "full_normalize": True,
        "groups": [
            {
                "components": [
                    {
                        "interpolation": 1,
                        "interpolation_style": 1,
                        "keyframes": [
                            {"position": 0, "wave_data": base64.b64encode(packed).decode("ascii")}
                        ],
                        "type": "Wave Source",
                    }
                ]
            }
        ],
        "name": "Ramp",
        "remove_all_dc": True,
        "version": "1.6.4",
    }
    assert _section("wavetables") == [wavetable] * 3


def test_each_lfo_and_each_warp_is_a_two_point_line() -> None:
    """Eight LFO shapes and three warp shapes, each the same straight line under its own name."""
    assert _section("lfos") == [_line(f"Line {number}") for number in range(1, 9)]
    assert _section("custom_warps") == [_line(f"Line {number}") for number in range(1, 4)]


def test_the_sample_is_a_sixteen_sample_ramp_and_each_random_source_has_the_save_s_seed() -> None:
    """Sixteen 16-bit values from -8000 in thousands, at 44.1 kHz; three seeds of 4."""
    values = [
        -8000,
        -7000,
        -6000,
        -5000,
        -4000,
        -3000,
        -2000,
        -1000,
        0,
        1000,
        2000,
        3000,
        4000,
        5000,
        6000,
        7000,
    ]
    sample = {
        "length": 16,
        "name": "Ramp",
        "sample_rate": 44100,
        "samples": base64.b64encode(struct.pack("<16h", *values)).decode("ascii"),
    }
    assert _section("sample") == sample
    assert _section("random_values") == [{"seed": 4}, {"seed": 4}, {"seed": 4}]


def test_the_text_is_written_for_a_map_holding_a_key_the_committed_list_lacks() -> None:
    """A census on a newer Vital writes all three files, so the text needs no model to exist.

    The preset's models hold a key to the committed key list and refuse this text; the map alone
    is enough to write it, with the new parameter at its default.
    """
    committed = parameter_map()
    last = committed.parameters[-1]
    added = last.model_copy(
        update={
            "parameter": last.parameter.model_copy(update={"id": ParameterId("zz_a_newer_key")}),
            "host_id": "zz_a_newer_key",
        }
    )
    newer = ParameterMap(
        instrument=committed.instrument,
        vital_version="9.9.9",
        host=committed.host,
        machine=committed.machine,
        parameters=(*committed.parameters, added),
    )
    text = start_text(newer)
    settings = json.loads(text)["settings"]
    assert settings["zz_a_newer_key"] == last.preset_default
    assert json.loads(text)["synth_version"] == "9.9.9"
    assert settings["wavetables"][0]["version"] == "9.9.9"
    with pytest.raises(UnknownSettingError) as caught:
        loads(text)
    assert caught.value.key == "zz_a_newer_key"
